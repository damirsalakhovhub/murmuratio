'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({window: {}});
vm.runInContext(fs.readFileSync(path.join(root, 'web/now.js'), 'utf8'), context);
const {credits} = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/adapters/codex-credit-header.json')));
const reserved = context.codexCreditDisplay({...credits, reserved_until: new Date(2026, 11, 1).getTime() / 1000});
assert.equal(reserved.value, 48000);
assert.equal(reserved.label, 'credits for December');
assert.equal(reserved.reserved, true);
const december = context.codexCreditDisplay({...credits, month_left: credits.balance});
assert.equal(december.value, credits.balance);
assert.equal(december.label, 'credits left in December');
assert.equal(december.reserved, false);
const plain = context.codexCreditDisplay({balance: credits.balance});
assert.equal(plain.value, credits.balance);
assert.equal(plain.label, 'credits');
console.log('Credit header: 3 states passed');
